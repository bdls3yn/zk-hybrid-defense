const rnd=()=>BigInt('0x'+crypto.randomBytes(31).toString('hex'));
const ctOf=(tag)=>BigInt('0x'+crypto.createHash('sha256').update(tag).digest('hex')); // stand-in 32-byte digest (only its binding matters)
function flat(p,pub){return [p.pi_a[0],p.pi_a[1],p.pi_b[0][1],p.pi_b[0][0],p.pi_b[1][1],p.pi_b[1][0],p.pi_c[0],p.pi_c[1],...pub].map(x=>BigInt(x).toString());}
const times=[];
async function prove(amount,max,actor,chain,tag){
  const ct=ctOf(tag);
  const inp={amount:String(amount),secret:rnd().toString(),maxAmount:String(max),cipherHash:(ct%R).toString(),actor:String(actor),chainId:String(chain)};
  const t0=process.hrtime.bigint();
  const {proof,publicSignals}=await s.groth16.fullProve(inp,{type:'mem',data:wasm},{type:'mem',data:zkey});
  times.push(Number(process.hrtime.bigint()-t0)/1e6);
  return {f:flat(proof,publicSignals),ct:'0x'+ct.toString(16).padStart(64,'0')};
}
